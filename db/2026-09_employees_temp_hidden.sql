-- =====================================================================
--  K-CORE · Тип працівника (штатний/тимчасовий) + приховування з ростеру
--
--  НАВІЩО: тимчасових хлопців (наприклад, на разовий підряд) треба мати
--  змогу нормально додати в employees, а потім прибрати з ока в
--  основному списку команди (EmployeeList.jsx), не втрачаючи їх у
--  графіку виїздів, плануванні, вихідних та історії — там вони й далі
--  мають бути повністю вибираними, бо фізично продовжують працювати.
--
--  employment_type  — тег "штатний / тимчасовий" (інформаційний бейдж).
--  hidden_from_list — керує видимістю ЛИШЕ в основному ростері команди.
--                     Жоден інший запит у системі (графік, виїзди,
--                     вихідні, задачі, обладнання, історія руху) цей
--                     прапорець не враховує і враховувати не повинен.
--
--  Застосовувати в Supabase → SQL Editor.
-- =====================================================================

ALTER TABLE employees
  ADD COLUMN IF NOT EXISTS employment_type text NOT NULL DEFAULT 'staff'
    CHECK (employment_type IN ('staff', 'temporary')),
  ADD COLUMN IF NOT EXISTS hidden_from_list boolean NOT NULL DEFAULT false;
