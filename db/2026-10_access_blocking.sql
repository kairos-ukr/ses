-- =====================================================================
--  K-CORE · Блокування доступу працівника
--
--  НАВІЩО: людина звільнилась або тимчасово не повинна бачити CRM.
--  Видаляти працівника не можна — на ньому тримаються етапи, виїзди,
--  складські рухи й історія. Тому закриваємо лише вхід у програму:
--  у «Доступах» з'являється кнопка «Заблокувати доступ», а людина
--  при вході (або коли повернеться на вкладку) бачить екран
--  «Доступ заблоковано».
--
--  access_blocked_at — коли заблоковано; порожньо = доступ є.
--  access_blocked_by — хто заблокував.
--
--  Важливо: це блокування інтерфейсу. Поки в базі немає правил доступу
--  (RLS), технічно підкована людина з ключем могла б звертатись до
--  даних напряму. Для звичайної роботи в CRM блокування спрацьовує.
--
--  Telegram-бот цей прапорець поки не враховує: якщо заблокованому
--  не треба отримувати сповіщення, приберіть йому Telegram ID у
--  «Працівниках».
--
--  Застосовувати в Supabase → SQL Editor.
-- =====================================================================

ALTER TABLE employees
  ADD COLUMN IF NOT EXISTS access_blocked_at timestamptz,
  ADD COLUMN IF NOT EXISTS access_blocked_by integer REFERENCES employees(id) ON DELETE SET NULL;


-- ---------------------------------------------------------------------
--  ПЕРЕВІРКА
-- ---------------------------------------------------------------------

-- Колонки на місці (очікується 2 рядки)
SELECT column_name, data_type
FROM information_schema.columns
WHERE table_schema = 'public' AND table_name = 'employees'
  AND column_name IN ('access_blocked_at', 'access_blocked_by');
