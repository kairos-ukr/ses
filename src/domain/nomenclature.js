// =====================================================================
//  K-CORE · Назва позиції разом із розділом складу
//
//  Програма показує позицію з її розділом: «Метизи Гвинт М8*20». Назви
//  тепер повні («Гвинт М8*20», а не «М8*20» — упорядкування 04.11.2026),
//  тож розділ, слово якого вже є в назві, вдруге не пишемо:
//  «Метизи Гвинт М8*20», а не «Метизи Гвинт Гвинт М8*20»;
//  «Електрозахист Автоматичний вимикач…», без «Автоматичні вимикачі».
// =====================================================================

// Основа слова без закінчення: «вимикачі» → «вимика», «щити» → «щит»
const stem = (w) => (w.length <= 4 ? w.slice(0, Math.max(3, w.length - 1)) : w.slice(0, Math.max(4, w.length - 2)));

/** path — назви категорій від кореня; name — назва позиції */
export function nomFullName(path, name) {
    const n = String(name || '').trim();
    const low = n.toLowerCase();
    const segs = (path || []).filter(seg => {
        const words = String(seg || '').toLowerCase().split(/[^\p{L}\p{N}-]+/u).filter(w => w.length >= 3);
        return !words.some(w => low.includes(stem(w)));
    });
    return [...segs, n].join(' ').trim();
}
